#!/usr/bin/env node
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const ROOT = resolve(import.meta.dirname, "..");
const OUTPUT = resolve(ROOT, "public/verified-repo-context.js");
const SOURCES = {
  zeppelin: resolve(ROOT, "benchmarks/demo-context/apache-zeppelin-live"),
  mypy: resolve(ROOT, "benchmarks/demo-context/python-mypy-live"),
};

function parseJsonl(text) {
  return text.split(/\r?\n/).filter(Boolean).map((line) => JSON.parse(line));
}

async function buildContext(source) {
  const [run, sourceText, alertsText] = await Promise.all([
    readFile(resolve(source, "run.json"), "utf8").then(JSON.parse),
    readFile(resolve(source, "source-prs.jsonl"), "utf8"),
    readFile(resolve(source, "alerts.jsonl"), "utf8"),
  ]);
  const suppressed = new Set(run.preflight?.suppressedPrNumbers || []);
  const prs = parseJsonl(sourceText).filter((pr) => !suppressed.has(pr.number)).map((pr) => ({
    id: String(pr.number),
    number: pr.number,
    title: pr.title,
    author: pr.author,
    url: pr.url,
    updatedAt: pr.updatedAt,
    paths: (pr.files || []).map((file) => file.filename),
    assumptions: [],
  }));
  const findings = parseJsonl(alertsText).map((record) => {
    const prediction = record.prediction;
    const isCoordination = prediction.verdict === "coordination";
    return {
    id: `${run.repository.replace("/", "-")}-live-${record.pullRequests.map((pr) => pr.number).sort((a, b) => a - b).join("x")}`,
    prIds: record.pullRequests.map((pr) => String(pr.number)),
    // Live deterministic alerts are hypotheses until replay or human causal
    // verification confirms them. Keep them in the review lane so only the
    // separately curated, evidence-backed case is presented as a conflict.
    verdict: isCoordination ? "coordination" : "review",
    category: prediction.category || "rollout",
    basis: prediction.basis || "merge-tree-textual-conflict",
    source: isCoordination ? "live repository preflight" : "live deterministic analysis",
    title: prediction.title,
    summary: prediction.summary,
    assumptionA: isCoordination
      ? "This PR expects its changed files to be merged while preserving its implementation and tests."
      : "This PR changes a declaration or behavior that the analyzer linked to the other PR.",
    assumptionB: isCoordination
      ? "The other PR changes the same merge surface and requires explicit conflict resolution."
      : "The other PR independently changes the same declaration, state, or consumer path.",
    consequence: prediction.invalidOutcome || (isCoordination
      ? "A mechanical merge conflict must be resolved before semantic compatibility can be evaluated."
      : prediction.summary),
    recommendation: isCoordination
      ? "Resolve the Git conflict on an integration branch and run both PRs' relevant tests."
      : "Review the bilateral evidence and run the relevant combined tests before merging.",
    retrievalFeatures: { sharedFiles: prediction.evidence || [] },
    evidence: (prediction.evidence || []).map((file, index) => ({
      id: `G${index + 1}`,
      side: "shared",
      file,
      quote: `Both PRs touch ${file}`,
    })),
    witnesses: (prediction.witnesses || []).slice(0, 2).map((witness) => ({
      title: witness.title || witness.type,
      explanation: witness.explanation,
      strength: witness.strength,
    })),
  };
  });
  return {
    generatedAt: run.generatedAt,
    repository: run.repository,
    summary: run.summary,
    preflight: {
      cleanPairs: run.preflight?.cleanPairs || 0,
      textualConflictPairs: run.preflight?.textualConflictPairs || 0,
      baseConflictPairs: run.preflight?.baseConflictPairs || 0,
    },
    prs,
    findings,
  };
}

const contexts = Object.fromEntries(await Promise.all(
  Object.entries(SOURCES).map(async ([key, source]) => [key, await buildContext(source)]),
));
const output = `// Generated by scripts/build-verified-demo-context.mjs from a live GitHub scan.\n` +
  `export const verifiedRepoContexts = ${JSON.stringify(contexts, null, 2)};\n`;
await writeFile(OUTPUT, output);
for (const [key, context] of Object.entries(contexts)) {
  console.log(`${key}: ${context.prs.length} PRs, ${context.findings.length} scanned findings.`);
}
console.log(`Wrote ${OUTPUT}.`);
